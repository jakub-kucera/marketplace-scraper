import pandas as pd, numpy as np
pd.set_option('display.width', 200); pd.set_option('display.max_colwidth', 90)
df = pd.read_csv('mb/macbook_ads.csv')
print(df.shape)
print(df.dtypes)
print("\n--- per marketplace/query ---")
print(df.groupby(['marketplace','query_id']).agg(n=('id','size'), price_med=('price','median'), price_min=('price','min'), price_max=('price','max')))
print("\n--- delivery status ---")
print(df.status.value_counts())
print("\n--- dup ad ids? ---", df.id.duplicated().sum())
b = df[df.marketplace=='bazos'].copy()
print("\n--- bazos short_description length ---")
print(b.short_description.fillna('').str.len().describe())
print("\n--- name length ---"); print(b.name.str.len().describe())
print("\n--- price describe ---"); print(b.price.describe())
print("\n--- sample of names (random 30) ---")
for n in b.name.sample(30, random_state=1): print("  ", n)
